// Synthetic scans only; use python -m scripts.documents_preview on port 8767.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const root='http://127.0.0.1:8767';
  try{
    const course=await(await context.request.post(root+'/api/courses',{data:{name:'取消处理 · 合成资料验收'}})).json();
    await page.goto(root);
    await page.locator('#documents .empty').filter({hasText:'资料库是空的'}).waitFor();
    await page.locator('#course').selectOption(course.id);
    await page.locator('#files').setInputFiles('data/ocr-test-fixtures/scanned-learning.pdf');
    const upload=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith(`/api/courses/${course.id}/documents`));
    await page.locator('#upload-button').click();
    const uploaded=await upload;
    assert.equal(uploaded.status(),202);
    const doc=await uploaded.json();
    await page.locator('.doc-progress').filter({hasText:'OCR'}).waitFor();
    const cancelled=page.waitForResponse(r=>r.url().endsWith(`/api/documents/${doc.id}/cancel`));
    await page.locator('.document-cancel').click();
    assert.equal((await cancelled).status(),202);
    await page.locator('.document label small').filter({hasText:/^已取消/}).waitFor();
    assert.equal(await page.locator('.document-cancel').count(),0);
    await page.locator('#upload-button:not([disabled])').waitFor();
    const cachedRoot=`data/documents-browser-check/ocr/${doc.id}`;
    const cacheFiles=fs.readdirSync(cachedRoot).filter(name=>name.endsWith('.json'));
    assert.ok(cacheFiles.length>=1&&cacheFiles.length<8);
    const cachedTime=fs.statSync(`${cachedRoot}/${cacheFiles[0]}`).mtimeMs;
    const cancelledDoc=(await(await context.request.get(`${root}/api/courses/${course.id}/documents`)).json())[0];
    assert.equal(cancelledDoc.status,'cancelled');
    assert.equal(cancelledDoc.chunk_count,0);
    assert.equal((await context.request.get(`${root}/api/documents/${doc.id}/file`)).status(),200);
    const noSources=await(await context.request.post(root+'/api/search',{data:{course_id:course.id,document_ids:[doc.id],question:'Machine Learning'}})).json();
    assert.deepEqual(noSources.sources,[]);
    await page.setViewportSize({width:390,height:844});
    await page.locator('#sidebar-toggle').click();
    await page.locator('.document').scrollIntoViewIfNeeded();
    fs.mkdirSync('docs/screenshots',{recursive:true});
    await page.screenshot({path:'docs/screenshots/cancelled-mobile.png',animations:'disabled'});
    await page.reload();
    await page.locator('.document label small').filter({hasText:/^已取消/}).waitFor({state:'attached'});
    await page.locator('#sidebar-toggle').click();
    const retry=page.locator('.document-actions .link-button').filter({hasText:'重试'});
    await retry.click();
    await page.locator('.document label small').filter({hasText:'可检索'}).waitFor({state:'attached',timeout:60000});
    assert.equal(fs.statSync(`${cachedRoot}/${cacheFiles[0]}`).mtimeMs,cachedTime);
    assert.equal(fs.readdirSync(cachedRoot).filter(name=>name.endsWith('.json')).length,8);
    const search=await(await context.request.post(root+'/api/search',{data:{course_id:course.id,document_ids:[doc.id],question:'机器学习 Machine Learning'}})).json();
    assert.ok(search.sources.length>0);
    await page.locator('.document-delete').click();
    await page.locator('#delete-document-confirm').click();
    await page.locator('#documents .empty').filter({hasText:'还没有资料'}).waitFor();
    assert.equal(fs.existsSync(cachedRoot),false);
    assert.deepEqual(errors,[]);
    const result={cancel_button_stops_ocr:true,cancelled_has_no_search_sources:true,original_file_kept:true,completed_pages_cached:cacheFiles.length,reload_keeps_cancelled_state:true,retry_reuses_cache:true,mobile_layout:true,delete_cleans_cache:true,javascript_errors:errors};
    fs.writeFileSync('docs/evaluation-cancel-ui.json',JSON.stringify(result,null,2)+'\n');
    console.log(JSON.stringify(result,null,2));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
